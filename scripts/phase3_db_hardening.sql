-- ============================================================
-- 6. HARDENING: Materialized view — active incident summary
-- Refreshed periodically for dashboard performance
-- ============================================================
CREATE MATERIALIZED VIEW IF NOT EXISTS mv_incident_summary AS
SELECT
    fi.site_id,
    fi.status,
    COUNT(*) AS count,
    MIN(fi.created_at) AS oldest,
    MAX(fi.created_at) AS newest,
    AVG(EXTRACT(EPOCH FROM (COALESCE(fi.resolved_at, NOW()) - fi.created_at))/60)::NUMERIC(10,2) AS avg_resolution_min
FROM fleet_incidents fi
GROUP BY fi.site_id, fi.status
WITH DATA;

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_incident_summary ON mv_incident_summary(site_id, status);

COMMENT ON MATERIALIZED VIEW mv_incident_summary IS 'Pre-aggregated incident summary per site/status. REFRESH MATERIALIZED VIEW CONCURRENTLY mv_incident_summary;';

-- ============================================================
-- 7. HARDENING: Materialized view — DLQ depth per site
-- ============================================================
CREATE MATERIALIZED VIEW IF NOT EXISTS mv_dlq_depth AS
SELECT
    COALESCE((payload->>'site_id')::text, 'global') AS site_id,
    status,
    COUNT(*) AS depth,
    MAX(created_at) AS latest_entry
FROM dlq_hybrid
GROUP BY COALESCE((payload->>'site_id')::text, 'global'), status
WITH DATA;

CREATE UNIQUE INDEX IF NOT EXISTS idx_mv_dlq_depth ON mv_dlq_depth(site_id, status);

COMMENT ON MATERIALIZED VIEW mv_dlq_depth IS 'DLQ depth per site for observability. Refresh every 30s.';

-- ============================================================
-- 8. HARDENING: Retention policy helper view
-- Identifies old partitions eligible for archival
-- ============================================================
CREATE OR REPLACE VIEW v_telemetry_retention_audit AS
SELECT
    schemaname,
    tablename,
    pg_size_pretty(pg_total_relation_size(schemaname||'.'||tablename)) AS partition_size,
    CASE
        WHEN tablename ~ 'y(\d{4})m(\d{2})' THEN
            to_date(
                substring(tablename from 'y(\d{4})') || '-' ||
                substring(tablename from 'm(\d{2})') || '-01',
                'YYYY-MM-DD'
            )
        ELSE NULL
    END AS partition_month,
    CASE
        WHEN to_date(
            substring(tablename from 'y(\d{4})') || '-' ||
            substring(tablename from 'm(\d{2})') || '-01',
            'YYYY-MM-DD'
        ) < NOW() - INTERVAL '3 months'
        THEN 'ELIGIBLE_FOR_ARCHIVE'
        ELSE 'RETAIN'
    END AS retention_status
FROM pg_tables
WHERE schemaname = 'public' AND tablename LIKE 'telemetry_logs_y%'
ORDER BY partition_month DESC;

COMMENT ON VIEW v_telemetry_retention_audit IS 'Identifies telemetry partitions older than 3 months for archival';

