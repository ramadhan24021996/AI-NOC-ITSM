-- 11. VALIDATION: Verify orphan state consistency
-- fleet_incidents that are WAITING_APPROVAL without approval queue entry
-- ============================================================
CREATE OR REPLACE VIEW v_orphan_waiting_approvals AS
SELECT fi.incident_id, fi.status, fi.created_at
FROM fleet_incidents fi
WHERE fi.status = 'WAITING_APPROVAL'
  AND NOT EXISTS (
      SELECT 1 FROM approval_queue aq
      WHERE aq.incident_id = fi.incident_id
        AND aq.status = 'PENDING'
  );

COMMENT ON VIEW v_orphan_waiting_approvals IS 'Incidents stuck in WAITING_APPROVAL without matching pending approval';

