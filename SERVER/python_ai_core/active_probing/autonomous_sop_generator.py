"""
Autonomous SOP & Runbook Generator Module
Automatically synthesizes completed incident investigations into structured Markdown SOP runbooks:
- Incident Title & Symptoms
- Active Diagnostic Probing Timeline
- Evidence & Hypothesis Elimination Matrix
- Validated Root Cause Analysis (RCA)
- Recommended Remediation & Rollback Strategy
- Human Review Approval Gate for KEDB publishing.
"""

from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any
from datetime import datetime, timezone


@dataclass
class GeneratedSOPDocument:
    sop_id: str
    title: str
    incident_id: str
    markdown_content: str
    status: str       # "DRAFT_AWAITING_HUMAN_REVIEW", "PUBLISHED"
    created_at: str


class AutonomousSOPGenerator:
    """Synthesizes verified incident investigations into enterprise SOP runbooks."""

    def generate_sop_from_investigation(
        self,
        incident_id: str,
        investigation_report: Dict[str, Any]
    ) -> GeneratedSOPDocument:

        sop_id = f"SOP-AUTO-{incident_id}"
        now_ts = datetime.now(timezone.utc).isoformat()

        title = investigation_report.get("incident_summary", f"Incident Investigation {incident_id}")
        symptoms = investigation_report.get("observed_symptoms", [])
        rca = investigation_report.get("validated_root_cause", "Unconfirmed Causal Anomaly")
        remediation = investigation_report.get("recommended_remediation", "Manual NOC Investigation")
        rollback = investigation_report.get("rollback_strategy", "Standard Service Reversion")
        timeline = investigation_report.get("probe_execution_timeline", [])
        confidence = investigation_report.get("confidence_score", 0.95)

        symptoms_md = "".join(f"- {s}\n" for s in symptoms)
        timeline_md = "".join(f"- {t}\n" for t in timeline)

        md_content = f"""# Standard Operating Procedure (SOP): {title}

**SOP ID:** `{sop_id}`  
**Incident ID:** `{incident_id}`  
**Generated Timestamp:** `{now_ts}`  
**Confidence Score:** `{round(confidence * 100, 1)}%`  
**Status:** `DRAFT_AWAITING_HUMAN_REVIEW`

---

## 1. Observed Incident Symptoms
{symptoms_md}
## 2. Active Diagnostic Probing Timeline
{timeline_md}
## 3. Validated Root Cause Analysis (RCA)
> **Root Cause:** {rca}

## 4. Recommended Remediation & Rollback Procedure
- **Remediation Action:** `{remediation}`
- **Rollback Strategy:** `{rollback}`

---
*Auto-generated by Enterprise Autonomous NOC AI Architect v8.0.0*
"""

        return GeneratedSOPDocument(
            sop_id=sop_id,
            title=title,
            incident_id=incident_id,
            markdown_content=md_content,
            status="DRAFT_AWAITING_HUMAN_REVIEW",
            created_at=now_ts
        )
